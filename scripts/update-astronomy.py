"""Refresh public NASA/JPL reference data. No runtime network dependency.
Sources and limitations are documented in docs/SOURCES.md.
"""
import concurrent.futures,json,pathlib,re,urllib.parse,urllib.request,time,hashlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
CACHE=ROOT/'artifacts/reference-cache'
CACHE.mkdir(parents=True,exist_ok=True)
EPOCH='2026-10-29'
AU_KM=149597870.7

def read(url):
 cache=CACHE/(hashlib.sha256(url.encode()).hexdigest()+'.txt')
 if cache.exists():return cache.read_text()
 for attempt in range(4):
  try:
   with urllib.request.urlopen(url,timeout=45) as response:content=response.read().decode()
   cache.write_text(content);return content
  except Exception:
   if attempt==3:raise
   time.sleep(2**attempt)
html=read('https://ssd.jpl.nasa.gov/planets/approx_pos.html')
pck=read('https://naif.jpl.nasa.gov/pub/naif/generic_kernels/pck/pck00011.tpc')
table=html.split('<h4>Table 1</h4>')[1].split('</pre>')[0]
names=['Mercury','Venus','EM Bary','Mars','Jupiter','Saturn','Uranus','Neptune']
ids=['mercury','venus','earth','mars','jupiter','saturn','uranus','neptune']
elements={}
for name,id in zip(names,ids):
 match=re.search(re.escape(name)+r'\s+([^\n]+)\n\s+([^\n]+)',table)
 elements[id]={'base':[float(v) for v in match[1].split()],'rate':[float(v) for v in match[2].split()]}
naif={'sun':10,**dict(zip(ids,[199,299,399,499,599,699,799,899])),'moon':301,'phobos':401,'deimos':402,'io':501,'europa':502,'ganymede':503,'callisto':504,'enceladus':602,'titan':606,'titania':703,'triton':801}
active='\n'.join(block.split('\\begintext')[0] for block in pck.split('\\begindata')[1:])
poles={}
for id,code in naif.items():
 entry={}
 for field,key in [('POLE_RA','ra'),('POLE_DEC','dec'),('PM','pm')]:
  matches=re.findall(r'BODY'+str(code)+'_'+field+r'\s*=\s*\(([^)]+)\)',active,re.I)
  entry[key]=[float(v.replace('D','E')) for v in matches[-1].split()]
 system=code//100
 degree=re.findall(r'BODY'+str(system)+r'_MAX_PHASE_DEGREE\s*=\s*(\d+)',active,re.I)
 width=int(degree[-1])+1 if degree else 2
 angleMatches=re.findall(r'BODY'+str(system)+r'_NUT_PREC_ANGLES\s*=\s*\(([^)]+)\)',active,re.I)
 values=[float(v.replace('D','E')) for v in angleMatches[-1].split()] if angleMatches else []
 entry['angles']=[values[i:i+width] for i in range(0,len(values),width)]
 for field,key in [('NUT_PREC_RA','periodicRA'),('NUT_PREC_DEC','periodicDEC'),('NUT_PREC_PM','periodicPM')]:
  matches=re.findall(r'BODY'+str(code)+'_'+field+r'\s*=\s*\(([^)]+)\)',active,re.I)
  entry[key]=[float(v.replace('D','E')) for v in matches[-1].split()] if matches else []
 poles[id]=entry
parents={'moon':399,'phobos':499,'deimos':499,'io':599,'europa':599,'ganymede':599,'callisto':599,'titan':699,'enceladus':699,'titania':799,'triton':899}

def moon_elements(item):
 id,parent=item
 params={'format':'json','COMMAND':"'%s'"%naif[id],'CENTER':"'500@%s'"%parent,'EPHEM_TYPE':"'ELEMENTS'",'START_TIME':"'%s'"%EPOCH,'STOP_TIME':"'2026-10-30'",'STEP_SIZE':"'1d'",'OUT_UNITS':"'KM-S'",'REF_PLANE':"'ECLIPTIC'",'CSV_FORMAT':"'YES'"}
 raw=json.loads(read('https://ssd.jpl.nasa.gov/api/horizons.api?'+urllib.parse.urlencode(params)))['result']
 row=raw.split('$$SOE')[1].strip().split('\n')[0].split(',')
 # EC QR IN OM W Tp N MA TA A AD PR after date columns.
 values=[float(v) for v in row[2:14]]
 return id,dict(zip(['eccentricity','periapsisKm','inclination','node','argument','periapsisJD','motionDegPerSecond','phase','trueAnomaly','semiMajorKm','apoapsisKm','periodSeconds'],values))
with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
 moons=dict(pool.map(moon_elements,parents.items()))
result='// Public NASA/JPL numeric reference snapshot; generated by scripts/update-astronomy.py.\n'
for name,data in [('JPL_ELEMENTS',elements),('IAU_POLES',poles),('SATELLITE_ELEMENTS',moons)]:
 result+='export const '+name+' = '+json.dumps(data,indent=2)+';\n'
(ROOT/'dist/src/astronomy-data.js').write_text(result)
print('Updated 8 JPL planetary element sets, 20 IAU pole/spin models, 11 satellite element snapshots at',EPOCH)
